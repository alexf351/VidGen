"""beat.py: builds one beat in Blender and renders it. Blender runs it headless:

    blender --background --factory-startup --python-exit-code 1 --python beat.py -- \
            --beat 3 --stage blockout --mode still --res 540x960 --samples 24 --out stills/b03_blockout.jpg

--mode still   one picture at --t seconds into the beat (default: the middle)
--mode frames  every frame of the beat into --out (a folder), skipping frames already there
--mode census  build and count, no render

Ends with one REPORT line: the census, objects outside the frame, warnings, render seconds.
Do not edit this file: scenes/beat_NN.py, cast.py and looks/ are where the video is made.
"""

import argparse
import importlib.util
import json
import os
import sys
import time

import bpy

WS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, WS)

import studio as S  # noqa: E402


def args():
    a = argparse.ArgumentParser()
    a.add_argument("--beat", type=int, required=True)
    a.add_argument("--stage", choices=S.STAGES, default="final")
    a.add_argument("--mode", choices=("still", "frames", "census"), default="still")
    a.add_argument("--t", type=float, default=None)
    a.add_argument("--res", default="540x960")
    a.add_argument("--samples", type=int, default=24)
    a.add_argument("--out", default="")
    a.add_argument("--fps", type=int, default=24)
    a.add_argument("--device", default="CPU")            # CPU | OPTIX | CUDA | HIP | ONEAPI
    a.add_argument("--engine", default="CYCLES")         # CYCLES | EEVEE
    return a.parse_args(sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else [])


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def set_resolution(o):
    r = bpy.context.scene.render
    w, h = (int(x) for x in o.res.lower().split("x"))
    r.resolution_x, r.resolution_y, r.resolution_percentage = w, h, 100


def setup_render(o):
    scene = bpy.context.scene
    r = scene.render
    if o.engine.upper().startswith("EEVEE"):
        r.engine = "BLENDER_EEVEE"
        scene.eevee.taa_render_samples = max(8, o.samples)
        return "EEVEE"
    r.engine = "CYCLES"
    c = scene.cycles
    c.samples = o.samples
    c.use_adaptive_sampling = True
    c.use_denoising = True
    c.denoiser = "OPENIMAGEDENOISE"
    c.max_bounces = 6
    r.use_persistent_data = True
    used = "CPU"
    if o.device.upper() != "CPU":
        prefs = bpy.context.preferences.addons["cycles"].preferences
        try:
            prefs.compute_device_type = o.device.upper()
            prefs.get_devices()
            cards = [d for d in prefs.devices if d.type == o.device.upper()]
            for d in prefs.devices:
                d.use = d.type == o.device.upper()
            if cards:
                c.device = "GPU"
                used = f"{o.device.upper()} ({', '.join(d.name for d in cards)})"
        except (TypeError, ValueError):
            pass
    if used == "CPU":
        c.device = "CPU"
    return used


def main():
    o = args()
    story = json.load(open(os.path.join(WS, "story.json"), encoding="utf-8"))
    beats = story["beats"]
    if not 1 <= o.beat <= len(beats):
        raise SystemExit(f"beat {o.beat}: the story has {len(beats)} beats")
    b = beats[o.beat - 1]
    ctx = S.Ctx(o.beat, b.get("line", ""), b.get("style", ""), b.get("seconds", 2.0), o.fps, o.stage)
    path = os.path.join(WS, "scenes", f"beat_{o.beat:02d}.py")
    if not os.path.isfile(path):
        raise SystemExit(f"scenes/beat_{o.beat:02d}.py does not exist yet")
    S.begin(ctx)
    look = os.path.join(WS, "looks", f"{ctx.style}.py")
    ctx.look = None
    if os.path.isfile(look):
        ctx.look = load(look, "look_" + ctx.style)
        ctx.look.setup(ctx)
    scene_mod = load(path, f"beat_{o.beat:02d}")
    scene_mod.build(ctx)
    S.finish()
    set_resolution(o)               # before the frame check: the frame is tall, not Blender's default wide
    census = S.census()
    scene = bpy.context.scene
    t = o.t if o.t is not None else ctx.seconds / 2
    scene.frame_set(ctx.frame(t))
    extra = {"beat": o.beat, "style": ctx.style, "frames": ctx.frames, "census": census,
             "outside_frame": S.outside_frame()}
    if o.mode == "census":
        S.report(**extra)
        return
    device = setup_render(o)
    extra["device"] = device
    r = scene.render
    t0 = time.time()
    if o.mode == "still":
        out = os.path.join(WS, o.out or f"stills/b{o.beat:02d}_{o.stage}.jpg")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        if out.lower().endswith(".png"):
            r.image_settings.file_format = "PNG"
            r.image_settings.color_mode = "RGB"
        else:
            r.image_settings.file_format = "JPEG"
            r.image_settings.quality = 88
        r.filepath = out
        bpy.ops.render.render(write_still=True)
        extra["still"] = os.path.relpath(out, WS).replace(os.sep, "/")
        extra["at_seconds"] = round(t, 2)
    else:
        folder = os.path.join(WS, o.out)
        os.makedirs(folder, exist_ok=True)
        r.image_settings.file_format = "PNG"
        r.image_settings.color_mode = "RGB"
        done = 0
        for f in range(1, ctx.frames + 1):
            dest = os.path.join(folder, f"{f:04d}.png")
            if os.path.isfile(dest) and os.path.getsize(dest) > 0:
                continue
            scene.frame_set(f)
            r.filepath = dest + ".tmp.png"
            t1 = time.time()
            bpy.ops.render.render(write_still=True)
            os.replace(dest + ".tmp.png", dest)
            done += 1
            print(f"FRAME {f}/{ctx.frames} {time.time() - t1:.1f}s", flush=True)
        extra["rendered_frames"] = done
    extra["render_seconds"] = round(time.time() - t0, 1)
    S.report(**extra)


main()
